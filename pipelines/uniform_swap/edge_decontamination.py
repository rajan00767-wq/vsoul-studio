"""Background-independent edge contamination detection and removal (V13.3.2 §5).

Why this module exists
----------------------
V13.3.1 delivered PA_11 with a blue fringe following the hair crown, and the
`white_edge_halo` gate scored it clean because that gate only looks for *white*
fringes. Measured on the delivered artifact
(`outputs/production_acceptance/PA_11_ShortBoy_Tie_debug/`):

* raw Qwen output: **0** pixels near the source backdrop colour
* assembled foreground (stage 17): **841** such pixels
* 100% of them within 25 px of the subject edge, 875/1000 within 9 px
* 813/1000 within 15 px of the hair mask
* their colour is (0,129,253) - *exactly* the source photo's backdrop blue

So the fringe is not generated by the model. It is source backdrop colour that
survived matting and was carried into the composite: classic alpha spill along
semi-transparent hair, where each boundary pixel is a blend of hair and the
backdrop it was photographed against.

The fix is therefore colour-unmixing at the boundary, not a white-specific
test. Everything here is driven by the *measured* source backdrop colour, so
blue, green, red, grey or any other studio backdrop behaves the same way.

Deliberately NOT done
---------------------
* no global desaturation - correction is confined to boundary pixels;
* genuinely coloured accessories and uniform trim are protected by requiring a
  pixel to both sit in the boundary band and match the backdrop closely;
* nothing is "cleaned" when the subject legitimately contains the backdrop
  colour away from its edge.
"""

from __future__ import annotations

import logging
from typing import Any, Dict, Optional, Tuple

import cv2
import numpy as np

logger = logging.getLogger(__name__)

__all__ = [
    "estimate_source_background_color",
    "build_boundary_trimap",
    "default_band_px",
    "detect_colored_edge_halo",
    "decontaminate_edges",
]


def default_band_px(height: int, width: int) -> int:
    """Boundary band width, scaled to the canvas.

    Measured on PA_11 (800x1024): a 9 px band captured 94.4% of the blue spill
    and left a visible fringe at the crown, where soft hair spreads the mixture
    further; 21 px captured 100% and reduced the post-repair residue from 119
    to 35 px. 2.5% of the short side reproduces that without hard-coding a
    figure that would mean something different at another output size.
    """
    return int(max(9, round(min(height, width) * 0.025)))


def estimate_source_background_color(
    source_rgb: np.ndarray,
    alpha: Optional[np.ndarray] = None,
) -> Tuple[Optional[Tuple[float, float, float]], float]:
    """Estimate the colour of the backdrop the source was photographed against.

    Returns ``(rgb, confidence)``. Confidence is the fraction of sampled
    background pixels that agree with the estimate, so a busy non-studio
    background yields a low value and callers can decline to act on it.
    """
    if source_rgb is None or source_rgb.size == 0:
        return None, 0.0
    h, w = source_rgb.shape[:2]

    if alpha is not None and alpha.shape[:2] == (h, w) and (alpha < 30).any():
        bg = alpha < 30
        # keep a margin from the subject so spill pixels do not define the estimate
        bg &= cv2.erode((bg).astype(np.uint8), np.ones((9, 9), np.uint8)) > 0
        samples = source_rgb[bg]
    else:
        k = max(8, int(min(h, w) * 0.05))
        samples = np.concatenate([
            source_rgb[:k, :].reshape(-1, 3),
            source_rgb[:, :k].reshape(-1, 3),
            source_rgb[:, -k:].reshape(-1, 3),
        ])

    if len(samples) < 50:
        return None, 0.0

    med = np.median(samples.astype(np.float32), axis=0)
    dist = np.linalg.norm(samples.astype(np.float32) - med[None, :], axis=1)
    confidence = float(np.mean(dist < 40.0))
    return (float(med[0]), float(med[1]), float(med[2])), confidence


def build_boundary_trimap(
    alpha: np.ndarray,
    band_px: int = 9,
) -> Dict[str, np.ndarray]:
    """Split the canvas into definite foreground, definite background, boundary.

    The boundary band is where alpha spill lives: pixels that are a mixture of
    subject and whatever was behind it.
    """
    fg = (alpha > 30).astype(np.uint8)
    k = np.ones((max(3, band_px), max(3, band_px)), np.uint8)
    inner = cv2.erode(fg, k)
    outer = cv2.dilate(fg, k)
    return {
        "definite_fg": inner > 0,
        "definite_bg": outer == 0,
        "boundary": (outer > 0) & (inner == 0),
    }


def detect_colored_edge_halo(
    composite_rgb: np.ndarray,
    alpha: np.ndarray,
    source_background_rgb: Optional[Tuple[float, float, float]],
    output_background_rgb: Tuple[int, int, int] = (255, 255, 255),
    band_px: Optional[int] = None,
    delta_e_threshold: float = 26.0,
    min_pixels: int = 150,
    hair_mask: Optional[np.ndarray] = None,
) -> Dict[str, Any]:
    """Detect boundary pixels contaminated by the SOURCE backdrop colour.

    Colour distance is computed in CIELAB so the test behaves consistently for
    any backdrop hue rather than keying on brightness like the white-only gate.

    Returns a check dict with `status` PASS / FAIL / UNCERTAIN, and a `mask` of
    the contaminated pixels.
    """
    h, w = composite_rgb.shape[:2]
    if band_px is None:
        band_px = default_band_px(h, w)
    empty = np.zeros((h, w), bool)
    if source_background_rgb is None:
        return {"status": "UNCERTAIN", "score": 0, "threshold": min_pixels,
                "details": "Source background colour not measurable; edge contamination not assessed",
                "mask": empty}

    src_bg = np.array(source_background_rgb, dtype=np.float32)
    out_bg = np.array(output_background_rgb, dtype=np.float32)

    # If the delivered backdrop is essentially the same colour as the source
    # backdrop, spill is indistinguishable from legitimate background and the
    # honest answer is that this cannot be measured.
    if float(np.linalg.norm(src_bg - out_bg)) < 40.0:
        return {"status": "UNCERTAIN", "score": 0, "threshold": min_pixels,
                "details": "Source and output backdrops are too similar to separate spill",
                "mask": empty}

    src_lab = cv2.cvtColor(src_bg.reshape(1, 1, 3).astype(np.uint8), cv2.COLOR_RGB2LAB)[0, 0].astype(np.float32)
    out_lab = cv2.cvtColor(out_bg.reshape(1, 1, 3).astype(np.uint8), cv2.COLOR_RGB2LAB)[0, 0].astype(np.float32)

    # An achromatic source backdrop (white, off-white, grey) has no colored chroma
    # to contaminate edges. Colored edge contamination requires a chromatic backdrop (blue, green, etc.).
    src_chroma = float(np.sqrt((src_lab[1] - 128.0) ** 2 + (src_lab[2] - 128.0) ** 2))
    if src_chroma < 10.0:
        return {"status": "PASS", "score": 0, "threshold": min_pixels,
                "details": f"Source backdrop is neutral achromatic (chroma={src_chroma:.1f} < 10.0); zero colored spill",
                "mask": empty}

    tri = build_boundary_trimap(alpha, band_px=band_px)
    lab = cv2.cvtColor(composite_rgb.astype(np.uint8), cv2.COLOR_RGB2LAB).astype(np.float32)
    d_src = np.linalg.norm(lab - src_lab[None, None, :], axis=2)

    # Spill is a MIXTURE of subject and backdrop, so most of it is nowhere near
    # the backdrop's exact colour. Measured on PA_11 after an exact-colour
    # repair: only 1 px remained within deltaE 26 of the backdrop, yet 8326 px
    # were still visibly blue. So detect by direction in the a*b* chroma plane
    # instead - a pixel pulled towards the backdrop's hue, away from the
    # delivered backdrop's, is contaminated at any mixing ratio.
    ab = lab[:, :, 1:3]
    src_dir = src_lab[1:3] - out_lab[1:3]
    norm = float(np.linalg.norm(src_dir))
    if norm < 1e-3:
        return {"status": "UNCERTAIN", "score": 0, "threshold": min_pixels,
                "details": "Source and output backdrops share a chroma direction; spill not separable",
                "mask": empty}
    src_dir = src_dir / norm
    # projection of each pixel's chroma (relative to the output backdrop) onto
    # the direction of the source backdrop
    proj = np.tensordot(ab - out_lab[1:3][None, None, :], src_dir, axes=([2], [0]))
    tinted = proj > (0.22 * norm)

    # Contaminated = in the boundary band, inside the kept subject, and either
    # close to the backdrop colour or measurably tinted towards its hue.
    # When hair_mask is available, confine spill detection to the hair perimeter
    # where photographic matting alpha spill actually occurs, protecting clothing and ties.
    if hair_mask is not None and np.any(hair_mask):
        hair_dil = cv2.dilate(hair_mask.astype(np.uint8), np.ones((max(7, band_px), max(7, band_px)), np.uint8)) > 0
        contaminated = tri["boundary"] & hair_dil & (alpha > 30) & ((d_src < delta_e_threshold) | tinted)
    else:
        contaminated = tri["boundary"] & (alpha > 40) & ((d_src < delta_e_threshold) | tinted)
        # Protect genuinely coloured regions: a real accessory or trim extends well
        # inside the subject, so drop any component that reaches past the band.
        if contaminated.any():
            n, labels = cv2.connectedComponents(contaminated.astype(np.uint8), connectivity=8)
            deep = tri["definite_fg"] & (tinted | (d_src < delta_e_threshold))
            for i in range(1, n):
                comp = labels == i
                if (comp & deep).sum() > 0.25 * comp.sum():
                    contaminated &= ~comp  # part of a real coloured object, not spill

    count = int(contaminated.sum())
    status = "FAIL" if count >= min_pixels else "PASS"
    return {
        "status": status, "score": count, "threshold": min_pixels,
        "details": (f"{count} boundary px match the source backdrop "
                    f"RGB({int(src_bg[0])},{int(src_bg[1])},{int(src_bg[2])}) within deltaE {delta_e_threshold}"),
        "mask": contaminated,
    }


def decontaminate_edges(
    composite_rgb: np.ndarray,
    alpha: np.ndarray,
    source_background_rgb: Optional[Tuple[float, float, float]],
    contaminated_mask: Optional[np.ndarray] = None,
    band_px: Optional[int] = None,
    hair_mask: Optional[np.ndarray] = None,
) -> Tuple[np.ndarray, np.ndarray, Dict[str, Any]]:
    """Remove source-backdrop spill from boundary pixels.

    Two complementary corrections, both confined to the contaminated mask:

    1. **Colour unmixing.** A spill pixel is ``obs = a*F + (1-a)*B`` for the
       source backdrop ``B``. Estimating the local foreground colour ``F`` from
       nearby clean interior pixels and solving for the mixing fraction lets the
       pixel be rewritten as the subject's own colour.
    2. **Alpha attenuation.** Where a pixel is almost entirely backdrop there is
       no subject colour to recover, so its alpha is reduced instead - the
       delivered backdrop shows through rather than the source's.

    Returns ``(rgb, alpha, info)``; inputs are not modified in place.
    """
    rgb = composite_rgb.astype(np.float32).copy()
    out_alpha = alpha.copy()
    if band_px is None:
        band_px = default_band_px(*composite_rgb.shape[:2])
    info: Dict[str, Any] = {"pixels_corrected": 0, "actions": []}
    if source_background_rgb is None:
        return rgb.astype(np.uint8), out_alpha, info

    if contaminated_mask is None:
        det = detect_colored_edge_halo(composite_rgb, alpha, source_background_rgb, band_px=band_px, hair_mask=hair_mask)
        contaminated_mask = det["mask"]
    if contaminated_mask is None or not contaminated_mask.any():
        return rgb.astype(np.uint8), out_alpha, info

    src_bg = np.array(source_background_rgb, dtype=np.float32)
    tri = build_boundary_trimap(alpha, band_px=band_px)

    # Local clean foreground colour: blur the interior and read it at the
    # boundary, so each spill pixel is repaired towards the hair or fabric
    # actually adjacent to it rather than a global average.
    if hair_mask is not None and np.any(hair_mask):
        clean = tri["definite_fg"] & hair_mask & ~contaminated_mask
        if clean.sum() < 25:
            clean = tri["definite_fg"] & ~contaminated_mask
    else:
        clean = tri["definite_fg"] & ~contaminated_mask

    if clean.sum() < 25:
        return rgb.astype(np.uint8), out_alpha, info

    src_img = rgb.copy()
    src_img[~clean] = 0.0
    wsum = cv2.GaussianBlur(clean.astype(np.float32), (0, 0), max(4.0, band_px * 1.4))
    csum = cv2.GaussianBlur(src_img, (0, 0), max(4.0, band_px * 1.4))
    local_fg = csum / np.maximum(wsum[:, :, None], 1e-6)

    ys, xs = np.where(contaminated_mask)
    obs = rgb[ys, xs]
    F = local_fg[ys, xs]
    B = src_bg[None, :]

    # Solve obs = a*F + (1-a)*B for a, least squares over the three channels.
    diff = F - B
    denom = np.sum(diff * diff, axis=1)
    num = np.sum((obs - B) * diff, axis=1)
    a_est = np.clip(np.where(denom > 1e-6, num / np.maximum(denom, 1e-6), 0.0), 0.0, 1.0)

    # Rewrite BOTH channels for every contaminated pixel. In the matting equation
    # stored color must be unmixed foreground F, with alpha attenuated where spill dominates.
    rgb[ys, xs] = np.clip(F, 0, 255)
    lab_obs = cv2.cvtColor(obs.reshape(-1, 1, 3).astype(np.uint8), cv2.COLOR_RGB2LAB).reshape(-1, 3).astype(np.float32)
    src_lab_val = cv2.cvtColor(src_bg.reshape(1, 1, 3).astype(np.uint8), cv2.COLOR_RGB2LAB)[0, 0].astype(np.float32)
    d_src_px = np.linalg.norm(lab_obs - src_lab_val[None, :], axis=1)
    alpha_scale = np.clip(np.minimum(a_est, d_src_px / 32.0), 0.0, 1.0)
    out_alpha[ys, xs] = np.clip(
        out_alpha[ys, xs].astype(np.float32) * alpha_scale, 0, 255).astype(np.uint8)

    recovered = int((a_est >= 0.35).sum())
    faded = int((a_est < 0.35).sum())
    info["pixels_corrected"] = int(contaminated_mask.sum())
    info["pixels_unmixed"] = recovered
    info["pixels_alpha_attenuated"] = faded
    info["actions"].append(
        f"decontaminated_colored_edge_halo ({recovered} unmixed to local foreground, "
        f"{faded} faded to the delivered backdrop)")
    logger.info("[EDGE_DECONTAMINATION] %s", info["actions"][-1])
    return np.clip(rgb, 0, 255).astype(np.uint8), out_alpha, info
